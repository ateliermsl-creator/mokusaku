const R = (x, y, w, h, rx = 0) => `<rect class="shp" x="${x}" y="${y}" width="${w}" height="${h}" rx="${rx}"/>`;
const P = (pts) => `<polygon class="shp" points="${pts}"/>`;
const L = (pts, w) => `<polyline class="shp ln" points="${pts}" style="stroke-width:${w}"/>`;
const HIT = (pts, w = 14) => `<polyline class="hit" points="${pts}" style="stroke-width:${w}"/>`;
const T = (x, y, s, anchor = 'start') => `<text x="${x}" y="${y}" text-anchor="${anchor}">${s}</text>`;

const part = (id, aria, ref, shapes) => ({ id, aria, ref, shapes });
/** 由 (x1,y1) 到 (x2,y2)、厚度 t 的斜向構件 */
const BEAM = (x1, y1, x2, y2, t = 10) => {
  const dx = x2 - x1, dy = y2 - y1, len = Math.hypot(dx, dy);
  const nx = (-dy / len) * (t / 2), ny = (dx / len) * (t / 2);
  const f = (v) => Math.round(v * 10) / 10;
  return P(`${f(x1 + nx)},${f(y1 + ny)} ${f(x2 + nx)},${f(y2 + ny)} ${f(x2 - nx)},${f(y2 - ny)} ${f(x1 - nx)},${f(y1 - ny)}`);
};

