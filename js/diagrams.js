export function renderDiagramSvg(d) {
  const parts = d.parts.map((p) =>
    `<g class="part" data-id="${p.id}" role="button" tabindex="0" aria-label="${p.aria}">${p.shapes}</g>`).join('');
  return `${parts}<g class="lbls">${d.labels.join('')}</g>`;
}
